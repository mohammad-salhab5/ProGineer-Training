def _clean_list(value):
    """
    يحول أي قيمة إلى list نظيفة من strings.
    """

    if value is None:
        return []

    if isinstance(value, str):
        value = [value]

    if not isinstance(value, list):
        return []

    cleaned = []

    for item in value:

        if not isinstance(item, str):
            continue

        item = item.strip()

        if not item:
            continue

        if item not in cleaned:
            cleaned.append(item)

    return cleaned


def _clean_relations(value):
    """
    تنظيف semantic_relations.
    """

    if not isinstance(value, list):
        return []

    cleaned = []

    for relation in value:

        if not isinstance(relation, dict):
            continue

        subject = str(
            relation.get("subject", "")
        ).strip()

        rel = str(
            relation.get("relation", "")
        ).strip()

        obj = str(
            relation.get("object", "")
        ).strip()

        if not subject or not rel or not obj:
            continue

        cleaned.append({
            "subject": subject,
            "relation": rel,
            "object": obj
        })

    return cleaned


def _fallback_result(question):
    """
    Fallback آمن إذا فشل optimizer.
    """

    question = (question or "").strip()

    return {
        "intent": "other",
        "question_type": "direct",
        "target": "",
        "attribute": "",
        "story_context": "",
        "story_surah_name": "",
        "entities": [],
        "concepts": [question] if question else [],
        "semantic_relations": [],
        "literal_anchor_queries": [],
        "search_queries": [question] if question else [],
    }


def _extract_json_from_text(text):
    """
    يستخرج JSON من نص قد يحتوي على markdown
    أو نص إضافي حول JSON.
    """

    if not text:
        return None

    # -----------------------------------------------------
    # 1. JSON داخل ```json
    # -----------------------------------------------------

    json_pattern = r"```json\s*([\s\S]*?)\s*```"

    match = re.search(
        json_pattern,
        text,
        re.IGNORECASE
    )

    if match:

        json_str = match.group(1).strip()

        try:
            return json.loads(json_str)

        except json.JSONDecodeError:
            pass

    # -----------------------------------------------------
    # 2. محاولة استخراج أول JSON object أو array
    #
    # [تعديل] كان بيدور بس عن "{" ... "}" (object). صار يدور
    # كمان عن "[" ... "]" (array) - لازم لأنه في استخدامات
    # جديدة (زي _retry_literal_anchors) بتتوقع array مباشر
    # كإخراج، مش object.
    # -----------------------------------------------------

    candidates = []

    obj_start, obj_end = text.find("{"), text.rfind("}")
    if obj_start != -1 and obj_end != -1 and obj_end > obj_start:
        candidates.append(text[obj_start:obj_end + 1])

    arr_start, arr_end = text.find("["), text.rfind("]")
    if arr_start != -1 and arr_end != -1 and arr_end > arr_start:
        candidates.append(text[arr_start:arr_end + 1])

    # لو الاثنين موجودين، نجرب الأقصر أولاً (أقل عرضة يكون فيه
    # نص زائد قبله/بعده أثّر على الـ boundaries)
    candidates.sort(key=len)

    for json_str in candidates:
        try:
            return json.loads(json_str)
        except json.JSONDecodeError:
            continue

    # -----------------------------------------------------
    # 3. محاولة parse النص كامل
    # -----------------------------------------------------

    try:
        return json.loads(text)

    except json.JSONDecodeError:
        return None


