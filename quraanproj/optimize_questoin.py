RETRY_ANCHOR_PROMPT = """
أنت خبير بالقرآن الكريم. مهمتك تذكّر ألفاظ أو عبارات قرآنية
حرفية (أو قريبة جدًا من اللفظ الأصلي) مرتبطة بسؤال وكيانات
معيّنة، لمساعدة نظام بحث دلالي يوصل للآيات الصحيحة.

قواعد صارمة:
- لا تجب عن السؤال نفسه، ولا تفسّره.
- لا تخترع ألفاظًا غير موجودة فعليًا بالقرآن. لو مش متأكد من
  اللفظ الدقيق لمشهد معين، لا تذكره.
- إذا كان في أكتر من مشهد/موقف قرآني محتمل مرتبط بالكيانات
  المذكورة، اذكر ألفاظًا من أكتر من مشهد، بدون ترجيح مين
  الإجابة الصح - الهدف توسيع البحث.
- تنبّه: بعض الكيانات المذكورة قد يكون اسمها شائعًا (من
  التفسير/الحديث) بس مش مذكور حرفيًا بنص القرآن (مثال: "الخضر"
  - القرآن بيصفه بـ "عبدا من عبادنا اتيناه رحمة ... وعلمناه من
  لدنا علما" بدل ما يسميه). بهاي الحالة اذكر اللفظ القرآني
  الفعلي البديل، مش الاسم الشائع نفسه.
- أعد النتيجة بصيغة JSON array من نصوص فقط، بدون أي شرح أو
  markdown. مثال: ["نص أول", "نص ثاني"]
- الحد الأقصى 5 عناصر. إذا ما تتذكر أي لفظ ذو صلة بثقة، أعد
  مصفوفة فاضية: []
"""


def _retry_literal_anchors(question, entities, concepts):
    """
    نداء ثاني مركّز فقط على استخراج literal anchors، يُستخدم
    كـ fallback عام (مش خاص بكيان محدد) لما المحاولة الأولى
    ضمن optimize_query الرئيسية ترجع فاضية.
    """

    entities_text = "، ".join(entities) if entities else "(غير محددة)"
    concepts_text = "، ".join(concepts[:8]) if concepts else "(غير محددة)"

    user_content = f"""
السؤال: {question}

الكيانات المذكورة: {entities_text}
مفاهيم مرتبطة بالسؤال: {concepts_text}
"""

    try:

        response = client.chat.completions.create(

            model="openai/gpt-oss-20b",

            messages=[
                {
                    "role": "system",
                    "content": RETRY_ANCHOR_PROMPT
                },
                {
                    "role": "user",
                    "content": user_content
                }
            ],

            temperature=0,

            max_tokens=300,

            reasoning_effort="low",

            reasoning_format="hidden",
        )

    except Exception as e:

        print(f"⚠️ Literal anchor retry failed: {e}")

        return []

    raw = response.choices[0].message.content

    parsed = _extract_json_from_text(raw.strip()) if raw else None

    if isinstance(parsed, list):
        return _clean_list(parsed)

    return []


